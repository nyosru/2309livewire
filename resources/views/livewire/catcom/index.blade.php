                        <h2 class="cat-title">От мысли<br>к действию — за 4 шага</h2>
                    </div>
                    <p class="cat-lead">Не стройте идеальный план на год. Создайте достаточно хороший план на ближайший отрезок.</p>
                </div>

                <div class="cat-steps">
                    <article class="cat-step">
                        <div class="cat-step-no">01</div><h3>Выгрузите</h3>
                        <p>Запишите всё, что требует внимания. Не сортируйте и не оценивайте — сначала освободите голову.</p>
                    </article>
                    <article class="cat-step">
                        <div class="cat-step-no">02</div><h3>Выберите</h3>
                        <p>Определите одну цель и не больше трёх приоритетов. Остальное не исчезнет — оно просто подождёт.</p>
                    </article>
                    <article class="cat-step">
                        <div class="cat-step-no">03</div><h3>Уменьшите</h3>
                        <p>Сформулируйте шаг, который можно завершить за один подход. Не «сделать сайт», а «написать заголовок первого экрана».</p>
                    </article>
                    <article class="cat-step">
                        <div class="cat-step-no">04</div><h3>Повторите</h3>
                        <p>В конце недели посмотрите на факты: что сделано, что мешало, что будет дальше. План можно менять — цель в том, чтобы двигаться.</p>
                    </article>
