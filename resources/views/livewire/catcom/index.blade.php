                <div class="cat-faq-list">
                    <details class="cat-faq-item" open>
                        <summary>Мне нужно планировать каждую минуту?</summary>
                        <p>Нет. Задача метода — не заполнить календарь, а убрать неопределённость. Вам достаточно знать приоритет и ближайшее действие.</p>
                    </details>
